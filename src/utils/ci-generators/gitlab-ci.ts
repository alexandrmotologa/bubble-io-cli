/**
 * Generator for a GitLab CI/CD pipeline that performs nightly Bubble.io backups.
 * Returns the YAML content as a string — no filesystem side-effects.
 */

export interface GitLabCIOptions {
  /** Bubble data type(s) to back up (e.g. "User", "Product") */
  dataType: string | string[];
  /** Bubble environment: version-test or version-live */
  env: string;
  /** Number of days to retain the backup artifact in GitLab */
  retentionDays: number;
  /** Output format for the backup file */
  format: 'json' | 'csv';
  /** bubble-io-cli version to install from npm. Defaults to "latest" */
  cliVersion: string;
}

/**
 * Generates the YAML content for a GitLab CI/CD pipeline file.
 */
export function generateGitLabCIWorkflow(opts: GitLabCIOptions): string {
  const {
    dataType,
    env,
    retentionDays,
    format,
    cliVersion,
  } = opts;

  const cliInstall = cliVersion === 'latest'
    ? 'bubble-io-cli'
    : `bubble-io-cli@${cliVersion}`;

  const types = Array.isArray(dataType) ? dataType : dataType.split(',').map(s => s.trim());
  const isMatrix = types.length > 1;

  const matrixYaml = isMatrix ? `
  parallel:
    matrix:
      - DATA_TYPE: [${types.map(t => `'${t}'`).join(', ')}]` : '';

  const typeResolutionBash = isMatrix
    ? `DATA_TYPE_RESOLVED="\${DATA_TYPE}"`
    : `DATA_TYPE_RESOLVED="\${DATA_TYPE:-'${types[0]}'}"`;

  return `# ============================================================
# Bubble.io Nightly Backup — auto-generated by bubble-io-cli
# ============================================================
#
# Required GitLab CI/CD Variables (Settings → CI/CD → Variables):
#   BUBBLE_APP_NAME   — your Bubble app name (e.g. my-app)
#   BUBBLE_API_KEY    — your Bubble Data API key (Masked)
#
# To schedule: CI/CD → Schedules → New schedule
# ============================================================

stages:
  - backup

variables:
  # Default environment, can be overridden when triggering manually
  ENVIRONMENT: '${env}'

bubble_backup:
  stage: backup
  image: node:20-alpine
  timeout: 30m${matrixYaml}
  
  before_script:
    - npm install -g ${cliInstall}
    - |
      bubble-io-cli config \\
        --app "\${BUBBLE_APP_NAME}" \\
        --key "\${BUBBLE_API_KEY}"
  
  script:
    - mkdir -p ./bubble-backups
    - ${typeResolutionBash}
    - |
      # Run backup and capture JSON result
      RESULT=$(bubble-io-cli backup \\
        --type "\${DATA_TYPE_RESOLVED}" \\
        --env "\${ENVIRONMENT}" \\
        --output "./bubble-backups" \\
        --format "${format}" \\
        --json)
        
    - |
      # Exit non-zero if backup reported failure
      SUCCESS=$(echo "\${RESULT}" | node -e "process.stdout.write(JSON.parse(require('fs').readFileSync('/dev/stdin','utf8')).success.toString())")
      if [ "\${SUCCESS}" != "true" ]; then
        echo "\${RESULT}" | node -e "const r=JSON.parse(require('fs').readFileSync('/dev/stdin','utf8')); console.error('❌ Backup failed:', r.error); process.exit(1)"
      fi
      
  artifacts:
    name: "bubble-backup-\${CI_JOB_ID}"
    paths:
      - bubble-backups/
    expire_in: ${retentionDays} days
    when: always
`;
}
